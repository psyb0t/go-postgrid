#!/bin/bash
# Collapses duplicate anyOf references in four mail creation responses.
# oapi-codegen otherwise emits duplicate union methods. The Go tool parses
# YAML and only replaces unions whose branches are the same bare reference.
# It also moves the shared search parameter's inline string branch into a
# named schema, avoiding an undefined N0 type without dropping either branch.
set -euo pipefail
trap 'on_error "$?" "$LINENO"' ERR

LOG_FILE="${LOG_FILE:-/tmp/$(basename "$0" .sh).log}"
exec > >(tee -a "$LOG_FILE") 2>&1

on_error() {
	local exit_code="$1"
	local line="$2"

	printf '{"level":"ERROR","file":"%s","line":%d,"msg":"command failed","exit_code":%d}\n' \
		"${BASH_SOURCE[1]}" "$line" "$exit_code" >&2
}

log() {
	local level="$1"
	shift

	jq -nc \
		--arg time "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" \
		--arg level "$level" \
		--arg file "${BASH_SOURCE[1]##*/}" \
		--arg line "${BASH_LINENO[0]}" \
		--arg func "${FUNCNAME[1]:-main}" \
		--arg msg "$*" \
		'{time:$time,level:$level,file:$file,line:($line|tonumber),func:$func,msg:$msg}' >&2
}

log INFO "collapsing redundant response unions"
go tool patch-spec
log INFO "saved api/openapi.patched.yaml"
